# Every time you add a dungeon just add another line below for the starting position 
# remember 1 equates to the 2nd map level because 0 equates to 1st map level 
level_start_positions: Dict[int, Dict[str, int]] = {      
    1: {"x": 5, "y": 4},
    2: {"x": 9, "y": 6}
}

###############################################################################################################

level: int = 0   # because 1st position/index in a list is a 0  

# selecting a map
data_map_choice: List[List[str]] = data_maps_library[level]     # Backend 
visual_map_choice: List[List[str]] = visual_maps_library[level]  # Frontend 

previousX: int | str = ""   # snapshot of current position just in case you hit into a wall 
previousY: int | str = ""   # Place holder 


def display_map(maps: List[List[str]]) -> None:
    """Print a formatted version of the map to the screen."""
    for x in range(len(maps)):
        map_row = str(maps[x]).replace(',', '').replace("'"," ").replace("."," ").replace("["," ").replace("]"," ")
        print(map_row)  


def clear_screen(Player: Any) -> str:
    """Refresh the screen, draw the player, and return the backend tile under them."""
    visual_map_choice[Player.y][Player.x] = "@"   # prints player position in the frontend 
    position = data_map_choice[Player.y][Player.x]  # initiate the players position in the backend 
    print("\033[H\033[J", end="")
    display_map(visual_map_choice) 
    return position


def solid_interaction(Player: Any, object: str) -> None:
    """Handle collisions with solid objects (walls, blocked tiles)."""
    visual_map_choice[Player.y][Player.x] = object 
    Player.x = previousX
    Player.y = previousY
    visual_map_choice[Player.y][Player.x] = "@" 
    print("\033[H\033[J", end="")
    display_map(visual_map_choice) 


def going_upstairs(Player: Any) -> None:
    """Move the player to the previous map level."""
    global level, data_map_choice,visual_map_choice   
    visual_map_choice[Player.y][Player.x] = "<"
    level = 0
    data_map_choice = data_maps_library[level]
    visual_map_choice = visual_maps_library[level]
    Player.x = 9
    Player.y = 4
    clear_screen(Player)
    print("You walk up the stairs")


def going_downstairs(Player: Any) -> None:
    """Move the player to the next map level."""
    global level, data_map_choice,visual_map_choice
    visual_map_choice[Player.y][Player.x] = ">" 
    level += 1
    data_map_choice = data_maps_library[level]
    visual_map_choice = visual_maps_library[level]

    if level in level_start_positions:
        coords = level_start_positions[level]
        Player.x = coords["x"]
        Player.y = coords["y"]
        clear_screen(Player)
        print("You walk down the stairs")


def flush(Player: Any) -> None:
    """Restore the tile behind the player so they don't leave '@' trails."""
    visual_map_choice[Player.y][Player.x] = "."


def recall_step(Player: Any) -> None:
    """Store the player's previous coordinates before movement."""
    global previousX, previousY
    previousX = Player.x
    previousY = Player.y
