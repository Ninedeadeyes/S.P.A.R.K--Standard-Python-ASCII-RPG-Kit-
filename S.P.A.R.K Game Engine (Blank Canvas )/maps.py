###############################################################################################################

level: int = 0   # because 1st position/index in a list is a 0  hence 1st map is 0 and the 2nd map is 1 etc etc 

data_map_choice: List[List[str]] = data_maps_library[level]
visual_map_choice: List[List[str]] = visual_maps_library[level]

previousX: int = ""                     # snapshot of current position just in case you hit into a wall (Place holder) 
previousY: int = ""

def display_map(maps: List[List[str]]) -> None:
    for x in range(len(maps)):
        map_row = str(maps[x]).replace(',', '').replace("'", " ").replace(".", " ").replace("[", " ").replace("]", " ")
        print(map_row)

def clear_screen(player: Player) -> str:
    visual_map_choice[player.y][player.x] = "@"    # prints player position in the frontend 
    position = data_map_choice[player.y][player.x]
    print("\033[H\033[J", end="")
    display_map(visual_map_choice)
    return position

def solid_interaction(player: Player, object: str) -> None:        # Used for anything you can't go through eg : wall
    visual_map_choice[player.y][player.x] = object
    player.x = previousX
    player.y = previousY
    visual_map_choice[player.y][player.x] = "@"    # prints player position in the frontend 
    print("\033[H\033[J", end="")
    display_map(visual_map_choice)

def going_upstairs(player: Player) -> None:
    global level, data_map_choice, visual_map_choice
    visual_map_choice[player.y][player.x] = "<"   # This is needed because the player leaves a trail of dots (eg:...)
    level = 0
    data_map_choice = data_maps_library[level]
    visual_map_choice = visual_maps_library[level]
    player.x = 9
    player.y = 4
    clear_screen(player)
    print("You walk up the stairs")

def going_downstairs(player: Player) -> None:
    global level, data_map_choice, visual_map_choice
    visual_map_choice[player.y][player.x] = ">"
    level += 1
    data_map_choice = data_maps_library[level]   # Backend 
    visual_map_choice = visual_maps_library[level]  # Frontend 

    if level in level_start_positions:             # generates hero starting position on the new map 
        coords = level_start_positions[level]
        player.x = coords["x"]
        player.y = coords["y"]
        clear_screen(player)
        print("You walk down the stairs")

def flush(player: Player) -> None:
    visual_map_choice[player.y][player.x] = "."   # it converts the previous position of the player back from @ to .  or it will leave a trail of @ @ @

def recall_step(player: Player) -> None:
    global previousX, previousY
    previousX = player.x                            # snapshot of current position just in case you hit into a wall 
    previousY = player.y
